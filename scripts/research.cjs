#!/usr/bin/env node
/* Research metadata pipeline.
 *
 *   node scripts/research.cjs build   validate every Research/<slug>/meta.json and regenerate:
 *                                      - its catalog/corpus.json item (then catalog/catalog.js)
 *                                      - the schema.org JSON-LD block in Research/<slug>/index.html
 *                                      - Research/index.json, the public research feed
 *   node scripts/research.cjs check   validate and report anything stale, without writing (exit 1 on problems)
 *
 * Articles without a meta.json keep their hand-written corpus item until they are migrated.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://amcamillo.github.io/thinkinfosec-hub/';
const AUTHOR_URL = 'https://www.linkedin.com/in/amcamillo/';
// The publisher's own site is never a citation.
const PUBLISHER_HOST = /(^|\.)thinkinfosec\.org$/;
const LD_START = '<!-- research-meta:start (generated by scripts/research.cjs) -->';
const LD_END = '<!-- research-meta:end -->';
const WPM = 230;

const REQUIRED = ['id', 'slug', 'title', 'summary', 'published', 'author', 'pillar', 'people', 'processes', 'tech', 'themes', 'tags', 'regions', 'caveats'];
const ALLOWED = new Set(REQUIRED.concat(['$schema', 'headline', 'updated', 'cover', 'frameworks', 'vendors', 'featured']));
const SLUG = /^[a-z0-9][a-z0-9-]*$/;
// Inside the article folder: no leading '/', and no segment may start with '.', which rules out '..'.
const COVER = /^[a-z0-9_-][a-z0-9._-]*(\/[a-z0-9_-][a-z0-9._-]*)*\.(webp|png|jpe?g|svg)$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;

function readJson(p) { return JSON.parse(fs.readFileSync(p, 'utf8').replace(/^﻿/, '')); }
function eol(text) { return /\r\n/.test(text) ? '\r\n' : '\n'; }
function withEol(text, nl) { return nl === '\r\n' ? text.replace(/\r?\n/g, '\r\n') : text; }

function vocab(tax) {
  const ids = (list) => new Set((list || []).map((x) => x.id));
  return {
    people: ids(tax.people), processes: ids(tax.processes), tech: ids(tax.techDomains),
    themes: ids(tax.themes), frameworks: ids(tax.frameworks), regions: ids(tax.regions),
    pillars: ids(tax.pillars),
  };
}

/** Returns a list of human-readable problems; empty means valid. */
function validate(meta, tax, folder) {
  const v = vocab(tax);
  const errs = [];
  const isStrArr = (a) => Array.isArray(a) && a.every((x) => typeof x === 'string');
  for (const k of REQUIRED) if (meta[k] === undefined) errs.push(`missing "${k}"`);
  for (const k of Object.keys(meta)) if (!ALLOWED.has(k)) errs.push(`unknown field "${k}"`);
  if (meta.id !== undefined && !/^research-[a-z0-9-]+$/.test(meta.id)) errs.push('id must look like research-<slug>');
  if (meta.slug !== undefined && meta.slug !== folder) errs.push(`slug "${meta.slug}" must equal folder "${folder}"`);
  if (typeof meta.title === 'string' && (meta.title.length < 3 || meta.title.length > 90)) errs.push('title must be 3-90 characters');
  if (typeof meta.summary === 'string' && (meta.summary.length < 30 || meta.summary.length > 240)) errs.push('summary must be 30-240 characters');
  for (const k of ['published', 'updated']) if (meta[k] !== undefined && !DATE.test(meta[k])) errs.push(`${k} must be YYYY-MM-DD`);
  if (meta.updated && meta.published && meta.updated < meta.published) errs.push('updated is earlier than published');
  if (meta.pillar !== undefined && !v.pillars.has(meta.pillar)) errs.push(`pillar "${meta.pillar}" is not in taxonomy.pillars`);
  const checkIds = (field, set, opts) => {
    const val = meta[field];
    if (val === undefined) return;
    if (!Array.isArray(val)) { errs.push(`${field} must be an array`); return; }
    if (new Set(val).size !== val.length) errs.push(`${field} has duplicates`);
    if (opts.min && val.length < opts.min) errs.push(`${field} needs at least ${opts.min}`);
    if (opts.max && val.length > opts.max) errs.push(`${field} allows at most ${opts.max}`);
    for (const x of val) if (!set.has(x)) errs.push(`${field}: "${x}" is not in the taxonomy`);
  };
  checkIds('people', v.people, {});
  checkIds('processes', v.processes, {});
  checkIds('tech', v.tech, { min: 1 });
  checkIds('themes', v.themes, { min: 1, max: 4 });
  checkIds('frameworks', v.frameworks, {});
  checkIds('regions', v.regions, { min: 1 });
  for (const field of ['tags', 'vendors']) {
    const val = meta[field];
    if (val === undefined) continue;
    if (!isStrArr(val)) { errs.push(`${field} must be an array of strings`); continue; }
    if (field === 'tags' && val.length > 12) errs.push('tags allows at most 12');
    for (const x of val) if (!SLUG.test(x)) errs.push(`${field}: "${x}" must be lowercase-kebab`);
  }
  if (meta.cover !== undefined && !COVER.test(meta.cover)) errs.push('cover must be an image path inside the article folder');
  if (meta.caveats !== undefined) {
    const c = meta.caveats;
    if (typeof c !== 'object' || c === null || typeof c.ai_assisted !== 'boolean' || typeof c.not_legal_advice !== 'boolean' || Object.keys(c).length !== 2) {
      errs.push('caveats must be { ai_assisted: boolean, not_legal_advice: boolean }');
    }
  }
  return errs;
}

function mainHtml(html) {
  const m = html.match(/<main[\s\S]*?<\/main>/i);
  return m ? m[0] : html;
}
function decode(s) {
  return s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;|&rsquo;|&lsquo;/g, "'").replace(/&nbsp;/g, ' ');
}
function textOf(html) { return decode(html.replace(/<(script|style)[\s\S]*?<\/\1>/gi, ' ').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim(); }

/** External links cited in the article body, first mention order, de-duplicated. */
function extractSources(html) {
  const out = [];
  const seen = new Set();
  const re = /<a\b[^>]*href="(https?:\/\/[^"]+)"[^>]*>([\s\S]*?)<\/a>/gi;
  let m;
  while ((m = re.exec(mainHtml(html)))) {
    const url = decode(m[1]);
    if (url.startsWith(SITE) || url.startsWith(AUTHOR_URL)) continue;
    const key = url.replace(/#.*$/, '');
    if (seen.has(key)) continue;
    seen.add(key);
    let host = '';
    try { host = new URL(url).hostname.replace(/^www\./, ''); } catch (e) { continue; }
    if (PUBLISHER_HOST.test(host)) continue;
    out.push({ url, host, text: textOf(m[2]).slice(0, 160) });
  }
  return out;
}

function readingMinutes(html) {
  return Math.max(1, Math.round(textOf(mainHtml(html)).split(' ').filter(Boolean).length / WPM));
}

function corpusItem(meta) {
  const item = {
    id: meta.id, title: meta.title, kind: 'research', origin: 'hub', pillar: meta.pillar,
    people: meta.people, processes: meta.processes, tech: meta.tech,
    link: `Research/${meta.slug}/`, description: meta.summary, date: meta.updated || meta.published,
  };
  if (meta.featured) item.featured = true;
  return item;
}

function labels(list, ids) {
  const by = new Map((list || []).map((x) => [x.id, x.label || x.name]));
  return ids.map((id) => by.get(id)).filter(Boolean);
}

function jsonLd(meta, tax, sources) {
  const url = `${SITE}Research/${meta.slug}/`;
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'Report',
    headline: meta.headline || meta.title,
    alternativeHeadline: meta.headline ? meta.title : undefined,
    description: meta.summary,
    url,
    mainEntityOfPage: url,
    datePublished: meta.published,
    dateModified: meta.updated || meta.published,
    image: meta.cover ? url + meta.cover : undefined,
    author: { '@type': 'Person', name: meta.author, url: AUTHOR_URL },
    publisher: { '@type': 'Organization', name: 'ThinkInfoSec', url: 'https://thinkinfosec.org', logo: `${SITE}assets/brand/logo-192.webp` },
    isAccessibleForFree: true,
    inLanguage: 'en',
    keywords: labels(tax.themes, meta.themes).concat(labels(tax.frameworks, meta.frameworks || []), meta.tags).join(', '),
    about: labels(tax.techDomains, meta.tech).map((name) => ({ '@type': 'Thing', name })),
    spatialCoverage: labels(tax.regions, meta.regions).map((name) => ({ '@type': 'Place', name })),
    citation: sources.map((s) => s.url),
    creativeWorkStatus: 'Published',
    disclaimer: [meta.caveats.ai_assisted ? 'AI-assisted research.' : '', meta.caveats.not_legal_advice ? 'This is not legal advice.' : ''].filter(Boolean).join(' ') || undefined,
  };
  return JSON.parse(JSON.stringify(ld));
}

function injectLd(html, ld) {
  const json = JSON.stringify(ld, null, 2).replace(/</g, '\\u003c');
  const block = `${LD_START}\n<script type="application/ld+json">\n${json}\n</script>\n${LD_END}`;
  const nl = eol(html);
  const s = html.indexOf(LD_START);
  const e = html.indexOf(LD_END);
  let out;
  if (s !== -1 && e !== -1) out = html.slice(0, s) + block + html.slice(e + LD_END.length);
  else {
    const i = html.search(/<\/head>/i);
    if (i === -1) throw new Error('no </head> to inject into');
    out = html.slice(0, i) + block + '\n' + html.slice(i);
  }
  return withEol(out.replace(/\r\n/g, '\n'), nl);
}

function feedEntry(meta, sources, minutes) {
  const url = `${SITE}Research/${meta.slug}/`;
  const e = {
    id: meta.id, slug: meta.slug, url, title: meta.title, headline: meta.headline || meta.title, summary: meta.summary,
    published: meta.published, updated: meta.updated || meta.published, author: meta.author,
    cover: meta.cover ? url + meta.cover : null, reading_minutes: minutes,
    pillar: meta.pillar, people: meta.people, processes: meta.processes, tech: meta.tech,
    themes: meta.themes, frameworks: meta.frameworks || [], regions: meta.regions, tags: meta.tags, vendors: meta.vendors || [],
    caveats: meta.caveats, sources,
  };
  return e;
}

function asciiJson(obj) {
  return JSON.stringify(obj).replace(/[\u007f-￿]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
}

/** Computes every generated file. Returns { problems, writes: [{ file, text }] }. */
function plan(root) {
  root = root || ROOT;
  const taxPath = path.join(root, 'catalog/taxonomy.json');
  const corpusPath = path.join(root, 'catalog/corpus.json');
  const tax = readJson(taxPath);
  const corpusText = fs.readFileSync(corpusPath, 'utf8');
  const corpus = JSON.parse(corpusText.replace(/^﻿/, ''));
  const problems = [];
  const writes = [];
  const feed = [];

  const resDir = path.join(root, 'Research');
  const folders = fs.readdirSync(resDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  for (const folder of folders) {
    const metaPath = path.join(resDir, folder, 'meta.json');
    if (!fs.existsSync(metaPath)) continue;
    let meta;
    try { meta = readJson(metaPath); } catch (e) { problems.push(`${folder}/meta.json: invalid JSON (${e.message})`); continue; }
    const errs = validate(meta, tax, folder);
    if (errs.length) { errs.forEach((x) => problems.push(`${folder}/meta.json: ${x}`)); continue; }
    const pagePath = path.join(resDir, folder, 'index.html');
    if (!fs.existsSync(pagePath)) { problems.push(`${folder}: meta.json without index.html`); continue; }
    if (meta.cover && !fs.existsSync(path.join(resDir, folder, meta.cover))) problems.push(`${folder}: cover "${meta.cover}" not found`);
    const html = fs.readFileSync(pagePath, 'utf8');
    const sources = extractSources(html);
    writes.push({ file: pagePath, text: injectLd(html, jsonLd(meta, tax, sources)) });
    feed.push(feedEntry(meta, sources, readingMinutes(html)));

    const item = corpusItem(meta);
    const at = corpus.items.findIndex((x) => x.id === meta.id);
    if (at === -1) corpus.items.push(item); else corpus.items[at] = item;
  }

  feed.sort((a, b) => (b.published > a.published ? 1 : b.published < a.published ? -1 : 0));
  const nl = eol(corpusText);
  writes.push({ file: corpusPath, text: withEol(JSON.stringify(corpus, null, 2) + '\n', nl) });
  writes.push({ file: path.join(root, 'catalog/catalog.js'), text: 'window.THINKINFOSEC_CATALOG = ' + asciiJson({ taxonomy: tax, corpus }) + ';' });
  // Keep the checkout's line endings, so a CRLF working copy is not reported stale.
  const feedPath = path.join(resDir, 'index.json');
  const feedNl = fs.existsSync(feedPath) ? eol(fs.readFileSync(feedPath, 'utf8')) : '\n';
  writes.push({ file: feedPath, text: withEol(JSON.stringify({ version: 1, generated_from: 'Research/*/meta.json', items: feed }, null, 2) + '\n', feedNl) });
  return { problems, writes };
}

function run(mode) {
  const { problems, writes } = plan(ROOT);
  const stale = writes.filter((w) => !fs.existsSync(w.file) || fs.readFileSync(w.file, 'utf8') !== w.text);
  if (mode === 'build' && !problems.length) {
    stale.forEach((w) => fs.writeFileSync(w.file, w.text, 'utf8'));
    console.log(`research: ${writes.length - 3} briefing(s) with meta.json; wrote ${stale.length} file(s)`);
    stale.forEach((w) => console.log('  ' + path.relative(ROOT, w.file)));
    return 0;
  }
  problems.forEach((p) => console.error('error: ' + p));
  if (mode === 'check') stale.forEach((w) => console.error('stale: ' + path.relative(ROOT, w.file) + ' (run: node scripts/research.cjs build)'));
  const bad = problems.length || (mode === 'check' && stale.length);
  if (!bad) console.log('research: all metadata valid and generated files current');
  return bad ? 1 : 0;
}

module.exports = { validate, extractSources, readingMinutes, corpusItem, jsonLd, injectLd, plan, LD_START, LD_END };

if (require.main === module) {
  const mode = process.argv[2];
  if (mode !== 'build' && mode !== 'check') { console.error('usage: node scripts/research.cjs build|check'); process.exit(2); }
  process.exit(run(mode));
}
